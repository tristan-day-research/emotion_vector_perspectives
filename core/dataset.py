def validate_dataset(stories: pd.DataFrame, neutral: pd.DataFrame) -> dict:
    """Report the dataset's actual shape and flag deviations from expectations."""
    per_emotion_topic = stories.groupby(["emotion", "topic"]).size()
    per_emotion = stories.groupby("emotion").size()
    per_neutral_topic = neutral.groupby("topic").size()

    report = {
        "n_emotional_stories": int(len(stories)),
        "n_emotions": int(stories["emotion"].nunique()),
        "n_topics": int(stories["topic"].nunique()),
        "stories_per_emotion_topic": {
            int(k): int(v) for k, v in per_emotion_topic.value_counts().items()
        },
        "stories_per_emotion": {int(k): int(v) for k, v in per_emotion.value_counts().items()},
        "n_neutral_stories": int(len(neutral)),
        "n_neutral_topics": int(neutral["topic"].nunique()),
        "neutral_stories_per_topic": {
            int(k): int(v) for k, v in per_neutral_topic.value_counts().items()
        },
        "neutral_topics_match_emotional": bool(
            set(neutral["topic"]) == set(stories["topic"])
        ),
        "duplicate_example_ids": int(
            stories["example_id"].duplicated().sum() + neutral["example_id"].duplicated().sum()
        ),
    }

    warns: list[str] = []
    if report["n_emotions"] != EXPECTED_N_EMOTIONS:
        warns.append(f"expected {EXPECTED_N_EMOTIONS} emotions, found {report['n_emotions']}")
    if report["n_topics"] != EXPECTED_N_TOPICS:
        warns.append(f"expected {EXPECTED_N_TOPICS} topics, found {report['n_topics']}")
    if report["n_emotional_stories"] != EXPECTED_N_EMOTIONAL_STORIES:
        warns.append(
            f"expected {EXPECTED_N_EMOTIONAL_STORIES} emotional stories, "
            f"found {report['n_emotional_stories']}"
        )
    if report["n_neutral_stories"] != EXPECTED_N_NEUTRAL_STORIES:
        warns.append(
            f"expected {EXPECTED_N_NEUTRAL_STORIES} neutral stories, "
            f"found {report['n_neutral_stories']}"
        )
    if set(report["stories_per_emotion_topic"]) != {EXPECTED_STORIES_PER_EMOTION_TOPIC}:
        warns.append(
            "stories per (emotion, topic) is not uniformly "
            f"{EXPECTED_STORIES_PER_EMOTION_TOPIC}: {report['stories_per_emotion_topic']}"
        )
    if not report["neutral_topics_match_emotional"]:
        warns.append("neutral topics differ from emotional topics")
    if report["duplicate_example_ids"]:
        warns.append(f"{report['duplicate_example_ids']} duplicate example ids")

    report["warnings"] = warns
    return report


def format_validation_report(report: dict) -> str:
    lines = [
        "Dataset validation",
        f"  emotional stories : {report['n_emotional_stories']:,}",
        f"  emotions          : {report['n_emotions']}",
        f"  topics            : {report['n_topics']}",
        f"  stories/(emo,topic): {report['stories_per_emotion_topic']}",
        f"  stories/emotion   : {report['stories_per_emotion']}",
        f"  neutral stories   : {report['n_neutral_stories']:,}",
        f"  neutral topics    : {report['n_neutral_topics']} "
        f"(match emotional: {report['neutral_topics_match_emotional']})",
    ]
    if report["warnings"]:
        lines.append("  WARNINGS:")
        lines += [f"    - {w}" for w in report["warnings"]]
    else:
        lines.append("  all structural expectations met")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Topic-level splitting
# --------------------------------------------------------------------------- #

def _largest_remainder(proportions: tuple[float, ...], total: int) -> list[int]:
    """Allocate ``total`` items across ``proportions`` so the counts sum exactly."""
    raw = [p * total for p in proportions]
    counts = [int(np.floor(r)) for r in raw]
    remainder = total - sum(counts)
    order = np.argsort([-(r - np.floor(r)) for r in raw], kind="stable")
    for i in range(remainder):
        counts[int(order[i % len(counts)])] += 1
    return counts


@dataclass(frozen=True)
class TopicSplit:
    """A deterministic topic -> split assignment."""

    topic_to_split: dict[str, str]
    seed: int
    proportions: tuple[float, float, float]

    def topics_for(self, split: str) -> list[str]:
        return sorted(t for t, s in self.topic_to_split.items() if s == split)

    @property
    def counts(self) -> dict[str, int]:
        return {s: len(self.topics_for(s)) for s in SPLIT_NAMES}


def assign_topic_splits(
    topics: list[str],
    seed: int,
    proportions: tuple[float, float, float] = (0.70, 0.15, 0.15),
) -> TopicSplit:
    """Partition topics into train/validation/test deterministically.

    The assignment depends only on ``(sorted(topics), seed, proportions)``.
    """
    if len(proportions) != 3:
        raise ValueError("proportions must be (train, validation, test)")
    if not np.isclose(sum(proportions), 1.0):
        raise ValueError(f"proportions must sum to 1.0, got {sum(proportions)}")
    if any(p < 0 for p in proportions):
        raise ValueError("proportions must be non-negative")

    ordered = sorted(topics)
    rng = rng_for(seed, "topic_split", len(ordered))
    permuted = [ordered[i] for i in rng.permutation(len(ordered))]

    counts = _largest_remainder(tuple(proportions), len(ordered))
    mapping: dict[str, str] = {}
    cursor = 0
    for split, n in zip(SPLIT_NAMES, counts):
        for topic in permuted[cursor : cursor + n]:
            mapping[topic] = split
        cursor += n

    return TopicSplit(mapping, seed, tuple(proportions))


def apply_topic_split(df: pd.DataFrame, split: TopicSplit) -> pd.DataFrame:
    """Add a ``split`` column derived from each row's topic."""
    out = df.copy()
    out["split"] = out["topic"].map(split.topic_to_split)
    if out["split"].isna().any():
        unmapped = sorted(out.loc[out["split"].isna(), "topic"].unique())[:3]
        raise ValueError(f"topics without a split assignment, e.g. {unmapped}")
    return out


# --------------------------------------------------------------------------- #
# Subsampling
# --------------------------------------------------------------------------- #

def subsample_per_emotion(
    stories: pd.DataFrame,
    n_per_emotion: int | None,
    seed: int,
) -> pd.DataFrame:
    """Take ``n_per_emotion`` stories per emotion, stratified across all topics.

    Stratifying matters: a naive random subsample would give each emotion a
    different topic mix, and the train/val/test proportions would drift away
    from the configured ones. We give every topic an equal quota (largest
    remainder for the leftovers) and sample within topic.
    """
    if n_per_emotion is None:
        return stories.copy()

    n_topics = stories["topic"].nunique()
    if n_per_emotion < n_topics:
        warnings.warn(
            f"stories_per_emotion={n_per_emotion} < {n_topics} topics: each emotion will "
            "cover only a subset of topics, so per-split counts will vary between emotions."
        )

    pieces: list[pd.DataFrame] = []
    for emotion, group in stories.groupby("emotion", sort=True):
        rng = rng_for(seed, "subsample_emotion", emotion)
        topics = sorted(group["topic"].unique())
        available = int(group.groupby("topic").size().min())
        per_topic_cap = min(available, int(np.ceil(n_per_emotion / len(topics))))
        # Equal quota per topic, leftovers assigned to a random subset of topics.
        base, extra = divmod(n_per_emotion, len(topics))
        quotas = {t: min(base, per_topic_cap) for t in topics}
        for t in (topics[i] for i in rng.permutation(len(topics))[:extra]):
            quotas[t] = min(quotas[t] + 1, per_topic_cap)

        taken = []
        for topic, tgroup in group.groupby("topic", sort=True):
            k = quotas[topic]
            if k <= 0:
                continue
            trng = rng_for(seed, "subsample_story", emotion, topic)
            idx = trng.permutation(len(tgroup))[:k]
            taken.append(tgroup.iloc[np.sort(idx)])
        if taken:
            pieces.append(pd.concat(taken))

    out = pd.concat(pieces).sort_values(["emotion", "topic_id", "story_idx"])
    return out.reset_index(drop=True)


def subsample_neutral(
    neutral: pd.DataFrame,
    n_total: int | None,
    seed: int,
) -> pd.DataFrame:
    """Take ``n_total`` neutral stories, stratified across topics."""
    if n_total is None:
        return neutral.copy()

    topics = sorted(neutral["topic"].unique())
    base, extra = divmod(n_total, len(topics))
    rng = rng_for(seed, "subsample_neutral")
    quotas = {t: base for t in topics}
    for t in (topics[i] for i in rng.permutation(len(topics))[:extra]):
        quotas[t] += 1

    taken = []
    for topic, group in neutral.groupby("topic", sort=True):
        k = min(quotas[topic], len(group))
        if k <= 0:
            continue
        trng = rng_for(seed, "subsample_neutral_story", topic)
        idx = trng.permutation(len(group))[:k]
        taken.append(group.iloc[np.sort(idx)])

    out = pd.concat(taken).sort_values(["topic_id", "story_idx"])
    return out.reset_index(drop=True)


# --------------------------------------------------------------------------- #
# One-call assembly
# --------------------------------------------------------------------------- #

def build_example_table(
    emotions: list[str] | None,
    stories_per_emotion: int | None,
    neutral_stories: int | None,
    split_seed: int,
    split_proportions: tuple[float, float, float] = (0.70, 0.15, 0.15),
    revision: str | None = None,
    cache_dir: str | Path | None = None,
    include_neutral: bool = True,
) -> tuple[pd.DataFrame, TopicSplit, dict]:
    """Assemble the exact set of examples an extraction run will process.

    Returns ``(examples, topic_split, validation_report)`` where ``examples`` has
    one row per story with columns ``example_id, source, emotion, topic,
    topic_id, story_idx, story, content_sha1, split``.
    """
    stories = load_emotional_stories(revision, cache_dir)
    topic_to_id = {t: i for i, t in enumerate(canonical_topics(stories))}
    neutral = load_neutral_stories(revision, cache_dir, topic_to_id=topic_to_id)

    report = validate_dataset(stories, neutral)
    split = assign_topic_splits(sorted(topic_to_id), split_seed, split_proportions)

    if emotions is not None:
        known = set(stories["emotion"].unique())
        unknown = [e for e in emotions if e not in known]
        if unknown:
            raise ValueError(
                f"emotions not present in the dataset: {unknown}. "
                f"See data/emotions_171.txt for the full list."
            )
        stories = stories[stories["emotion"].isin(emotions)].copy()

    stories = subsample_per_emotion(stories, stories_per_emotion, split_seed)

    frames = [stories]
    if include_neutral:
        frames.append(subsample_neutral(neutral, neutral_stories, split_seed))

    examples = pd.concat(frames, ignore_index=True)
    examples = apply_topic_split(examples, split)
    # Deterministic global ordering -> deterministic sharding and resume behaviour.
    examples = examples.sort_values(
        ["source", "emotion", "topic_id", "story_idx"], na_position="first"
    ).reset_index(drop=True)
    return examples, split, report


def summarise_examples(examples: pd.DataFrame) -> str:
    """Human-readable breakdown of the assembled example table."""
    lines = [f"Examples selected: {len(examples):,}"]
    emo = examples[examples["source"] == "emotion"]
    neu = examples[examples["source"] == "neutral"]
    if len(emo):
        by_split = emo.groupby("split").size().reindex(SPLIT_NAMES, fill_value=0)
        per_emo = emo.groupby("emotion").size()
        lines.append(
            f"  emotional : {len(emo):,} across {emo['emotion'].nunique()} emotions "
            f"({per_emo.min()}-{per_emo.max()} per emotion)"
        )
        lines.append(
            "    by split: "
            + ", ".join(f"{s}={int(by_split[s]):,}" for s in SPLIT_NAMES)
        )
    if len(neu):
        by_split = neu.groupby("split").size().reindex(SPLIT_NAMES, fill_value=0)
        lines.append(f"  neutral   : {len(neu):,}")
        lines.append(
            "    by split: "
            + ", ".join(f"{s}={int(by_split[s]):,}" for s in SPLIT_NAMES)
        )
    return "\n".join(lines)
