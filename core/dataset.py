"""Loading and splitting of the pre-generated emotional-story dataset.

Data source (not generated by us)
---------------------------------
``ryancodrai/emotion-probes`` on the Hugging Face Hub, CC-BY-4.0, built by Ryan
Codrai following the methodology of Anthropic's "Emotion Concepts and their
Function in a Large Language Model" (Sofroniew et al., 2026).

Verified structure (revision as of 2026-08-14)::

    expression/stories.parquet          205,200 rows  [emotion, topic, story]
                                        = 171 emotions x 100 topics x 12 stories
    expression/neutral_stories.parquet    1,200 rows  [topic, story]
                                        = the same 100 topics x 12 stories

The neutral stories reuse the *same* 100 topics as the emotional stories, so a
single topic-level split partitions both consistently.

Splitting policy
----------------
We split by **topic**, never by individual story. Twelve stories share one
topic and are near-paraphrases of one scenario; a random story-level split
would leak a scenario across train and eval and inflate every metric.
"""

from __future__ import annotations

import hashlib
import re
import warnings
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from core.seeds import rng_for

HF_DATASET_ID = "ryancodrai/emotion-probes"
EXPRESSION_STORIES_FILE = "expression/stories.parquet"
EXPRESSION_NEUTRAL_FILE = "expression/neutral_stories.parquet"

#: Structure we expect to find; deviations are reported by :func:`validate_dataset`.
EXPECTED_N_EMOTIONS = 171
EXPECTED_N_TOPICS = 100
EXPECTED_STORIES_PER_EMOTION_TOPIC = 12
EXPECTED_N_EMOTIONAL_STORIES = 205_200
EXPECTED_N_NEUTRAL_STORIES = 1_200

SPLIT_NAMES = ("train", "validation", "test")


# --------------------------------------------------------------------------- #
# Loading
# --------------------------------------------------------------------------- #

def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def _content_hash(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:12]


def _load_parquet_via_hf(
    data_file: str,
    revision: str | None = None,
    cache_dir: str | Path | None = None,
) -> pd.DataFrame:
    """Load one parquet file from the Hub through ``datasets``."""
    from datasets import load_dataset

    ds = load_dataset(
        HF_DATASET_ID,
        data_files=data_file,
        split="train",
        revision=revision,
        cache_dir=str(cache_dir) if cache_dir else None,
    )
    return ds.to_pandas()


def dataset_revision(revision: str | None = None) -> str:
    """Resolve the dataset revision to a concrete commit sha (best effort)."""
    try:
        from huggingface_hub import dataset_info

        return dataset_info(HF_DATASET_ID, revision=revision).sha
    except Exception as exc:  # offline, no token, etc.
        warnings.warn(f"Could not resolve dataset revision sha: {exc}")
        return revision or "unknown"


def canonical_topics(stories: pd.DataFrame) -> list[str]:
    """Stable, config-independent topic ordering.

    Derived from the *full* story table (all 171 emotions), so selecting a
    subset of emotions never changes a topic's id or split assignment.
    """
    return sorted(stories["topic"].unique().tolist())


def load_emotional_stories(
    revision: str | None = None,
    cache_dir: str | Path | None = None,
) -> pd.DataFrame:
    """All 205,200 emotional stories with stable example ids.

    Returns columns: ``example_id, source, emotion, topic, topic_id, story_idx,
    story, content_sha1``.
    """
    df = _load_parquet_via_hf(EXPRESSION_STORIES_FILE, revision, cache_dir)
    missing = {"emotion", "topic", "story"} - set(df.columns)
    if missing:
        raise ValueError(f"{EXPRESSION_STORIES_FILE} missing columns: {sorted(missing)}")

    topics = canonical_topics(df)
    topic_to_id = {t: i for i, t in enumerate(topics)}

    # story_idx = position within (emotion, topic) in file order -> stable per revision.
    df = df.reset_index(drop=True)
    df["story_idx"] = df.groupby(["emotion", "topic"], sort=False).cumcount()
    df["topic_id"] = df["topic"].map(topic_to_id).astype(int)

    slugs = {e: _slug(e) for e in df["emotion"].unique()}
    if len(set(slugs.values())) != len(slugs):
        raise ValueError("Emotion name slugs collide; example ids would be ambiguous.")

    df["example_id"] = (
        "exp-"
        + df["emotion"].map(slugs)
        + "-t"
        + df["topic_id"].map("{:03d}".format)
        + "-s"
        + df["story_idx"].map("{:02d}".format)
    )
    df["source"] = "emotion"
    df["content_sha1"] = df["story"].map(_content_hash)

    cols = ["example_id", "source", "emotion", "topic", "topic_id", "story_idx", "story", "content_sha1"]
    return df[cols].copy()


def load_neutral_stories(
    revision: str | None = None,
    cache_dir: str | Path | None = None,
    topic_to_id: dict[str, int] | None = None,
) -> pd.DataFrame:
    """The 1,200 emotionally neutral stories used for nuisance-PC removal.

    ``topic_to_id`` should come from :func:`canonical_topics` on the emotional
    stories so that topic ids (and therefore splits) line up across both tables.
    """
    df = _load_parquet_via_hf(EXPRESSION_NEUTRAL_FILE, revision, cache_dir)
    missing = {"topic", "story"} - set(df.columns)
    if missing:
        raise ValueError(f"{EXPRESSION_NEUTRAL_FILE} missing columns: {sorted(missing)}")

    if topic_to_id is None:
        topic_to_id = {t: i for i, t in enumerate(sorted(df["topic"].unique().tolist()))}

    unknown = sorted(set(df["topic"]) - set(topic_to_id))
    if unknown:
        raise ValueError(
            f"{len(unknown)} neutral topics absent from the emotional-story topic list, "
            f"e.g. {unknown[:3]}. Topic ids/splits would be inconsistent."
        )

    df = df.reset_index(drop=True)
    df["story_idx"] = df.groupby("topic", sort=False).cumcount()
    df["topic_id"] = df["topic"].map(topic_to_id).astype(int)
    df["example_id"] = (
        "neu-t" + df["topic_id"].map("{:03d}".format) + "-s" + df["story_idx"].map("{:02d}".format)
    )
    df["source"] = "neutral"
    df["emotion"] = pd.NA
    df["content_sha1"] = df["story"].map(_content_hash)

    cols = ["example_id", "source", "emotion", "topic", "topic_id", "story_idx", "story", "content_sha1"]
    return df[cols].copy()


