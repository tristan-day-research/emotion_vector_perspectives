def gloss(token: str) -> str:
    """English gloss for a CJK token, or '' when it is not in the glossary."""
    return TOKEN_GLOSS.get(str(token).strip(), "")


def matches_chinese(token: str, emotion: str) -> bool:
    """Exact-equality match of ``token`` against ``emotion``'s Chinese renderings."""
    return str(token).strip() in EMOTION_ZH.get(emotion, [])


def matches_en_synonym(token: str, emotion: str) -> bool:
    """Exact-equality match against ``emotion``'s English near-synonyms."""
    return str(token).strip().lower() in {
        s.lower() for s in EMOTION_EN_SYNONYMS.get(emotion, [])
    }
