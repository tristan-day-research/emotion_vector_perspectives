"""Hand-written Chinese<->English reference data for reading Phase 4.

**This file is not pipeline output.** Everything in it is a human translation
judgement, written by hand, and it is kept in its own module precisely so that it
can be audited separately from anything the pipeline measured. Nothing here changes
a Phase 4 artefact; the notebook joins against it to (a) make the token tables
legible and (b) run a relaxed, cross-lingual version of GATE A.

Why this exists
---------------
The Jacobian-lens readouts at block 31 are 43-61% CJK by token count, and GATE A
asks an English question ("does the emotion's own English word appear in the
vector's top-12?"). Two separate things could sink that test:

1. **Script.** The readout names the concept in Chinese, so an English lemma cannot
   appear no matter how good the direction is.
2. **Exact-lemma matching.** The readout offers ``sorrow`` when the test wants
   ``sad``; a near-synonym is not a hit.

GATE A conflates the two. :data:`EMOTION_ZH` and :data:`EMOTION_EN_SYNONYMS` let the
notebook separate them by scoring three nested tiers against the same top-12 lists.

Pre-commitment protocol
-----------------------
The honest failure mode here is fishing: writing translations *after* seeing which
tokens appeared, so that the synonym lists are quietly fitted to the answer. To
avoid it:

* :data:`EMOTION_ZH` and :data:`EMOTION_EN_SYNONYMS` were written from the 171
  emotion words alone, in one pass, and saved to this file **before** any matching
  code was run against ``phase4_readouts.csv``.
* Matching is **exact set membership** (after stripping whitespace and lowercasing
  Latin), not substring or fuzzy matching. A generous list is therefore visible as a
  generous list rather than hidden in a matcher.
* Both lists are printed in full in ``RESULTS.md`` so a reader can judge the
  generosity themselves and re-score with a stricter list if they disagree.

**Disclosed contamination.** Before writing these lists the author had already seen
the PC-end and a-priori-axis readouts (the ~51 CJK tokens in the notebook's Phase 4
token panels), and the five GATE A emotions the pipeline scored HIT. The author had
**not** seen the per-emotion top-12 token lists for the 171 emotions, which is what
the relaxed GATE A scores. The per-emotion result is therefore clean; the PC-end
glosses are a reading aid and carry no inferential weight.

Known limitation: multi-character Chinese phrases below are often not single tokens
in Qwen's vocabulary, so they can never match. That biases the Chinese tier
*downwards* -- it can under-count hits, not invent them.
"""

